// Package imageasset 管理渲染期图片和 SVG 场景的加载、懒解码与有界缓存。
//
// 每个文档视图持有独立的 Store，零值可用且支持并发访问。同一资源的并发加载
// 按键合并，图片与内存印章共用位图预算，SVG 场景使用独立预算；结束时调用
// Close，关闭前已开始的加载可完成，但其结果不再回填缓存。
// 普通位图 LRU 上限为 64 MiB，另保留一个不超过 256 MiB 的大图旁路槽，
// 防止单条大图淘汰整个普通缓存；两者均计入编码数据及预计解码像素的权重。
// 固定资源失败使用最多 128 条的负缓存，取消、临时读取失败和当前绘制预算不足不缓存。
//
// 栅格图片在解码前通过 DecodeConfig 检查尺寸；LoadWithOptions 在缓存未命中时
// 向调用方预留像素额度。SVG 位图按目标像素需求栅格化并按尺寸分开缓存。
//
// 调用方提供资源读取器和 SVG 解析函数，本包不依赖 render、drawing 或 parser。
// 缓存返回的图片、原始编码字节及 SVG 场景均视为只读；场景的矢量嵌入与栅格化
// 由场景内部的同一把锁保护。页面放置、裁剪及印章预处理策略由调用方负责。
