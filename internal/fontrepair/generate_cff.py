#!/usr/bin/env python3
"""Generate CFF identifiers from Adobe 5176, pdftotext -layout output.

Usage: python3 generate_cff.py /tmp/5176.CFF.txt
Only the standard identifiers in appendices A/C are extracted.
"""
import json
import pathlib
import re
import sys

text = pathlib.Path(sys.argv[1]).read_text()
appendix_a = re.split(r"\f\s*Appendix A\s+Standard Strings", text)[-1]
appendix_a = re.split(r"\f\s*Appendix B", appendix_a)[0]
pair = r"(?<!\S)(\d+)\s+([A-Za-z.][A-Za-z0-9.]*|00[0-9]\.[0-9]+)"
names = {}
for sid, name in re.findall(pair, appendix_a):
    if int(sid) < 391 and name != "Appendix":
        names[int(sid)] = name
assert sorted(names) == list(range(391)), sorted(set(range(391)) - names.keys())


def charset(start, end, count):
    body = text.split(start)[1].split(end)[0]
    result = [0]
    for page in body.split("\f"):
        columns = [[], [], []]
        for line in page.splitlines():
            values = re.findall(pair, line)
            if not values or len(values) > 3:
                continue
            # Exclude page footers and headings.
            if any(name not in names.values() for _, name in values):
                continue
            for col, (sid, _) in enumerate(values):
                columns[col].append(int(sid))
        result.extend(value for column in columns for value in column)
    assert len(result) == count, (start, len(result))
    return result


expert = charset("Expert (SID / name)", "Expert Subset (SID / name)", 166)
subset = charset("Expert Subset (SID / name)", "Example CFF Font", 87)
lines = ["// Code generated by generate_cff.py; DO NOT EDIT.",
         "// 标准标识数据来自 Adobe 5176 附录 A/C。",
         "package fontrepair", "var standardStrings = []string{"]
lines += [json.dumps(names[sid]) + "," for sid in range(391)]
lines += ["}"]
for name, values in [("expertCharset", expert), ("expertSubsetCharset", subset)]:
    lines += ["var " + name + " = []uint16{" + ",".join(map(str, values)) + "}"]
pathlib.Path(__file__).with_name("cff_identifiers.go").write_text("\n".join(lines) + "\n")
