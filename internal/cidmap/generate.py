#!/usr/bin/env python3
"""Generate shared Adobe-GB1 data from a poppler-data installation.

Usage: python3 internal/cidmap/generate.py /usr/share/poppler
Only mapping data is used; no font or PDF implementation is imported.
"""
import hashlib
import json
import pathlib
import re
import struct
import sys
import zlib

source = pathlib.Path(sys.argv[1])
output = pathlib.Path(__file__).parent
glyph_path = "cidToUnicode/Adobe-GB1"
text_path = "cMap/Adobe-GB1/Adobe-GB1-UCS2"
glyph_data = (source / glyph_path).read_bytes()
text_data = (source / text_path).read_bytes()
glyphs = [int(line, 16) for line in glyph_data.splitlines()]
assert len(glyphs) == 30284
texts = {}
cmap = re.sub(r"%[^\r\n]*", "", text_data.decode())
for mode, body in re.findall(r"begin(bfchar|bfrange)\s+(.*?)\s+end\1", cmap, re.S):
    tokens = iter(re.findall(r"<[0-9a-fA-F]+>|\[|\]", body))
    for token in tokens:
        first = int(token[1:-1], 16)
        last = first if mode == "bfchar" else int(next(tokens)[1:-1], 16)
        target = next(tokens)
        array = target == "["
        base = 0 if array else int(target[1:-1], 16)
        for cid in range(first, last + 1):
            raw = bytes.fromhex(next(tokens)[1:-1]) if array else (base + cid - first).to_bytes(len(target[1:-1]) // 2, "big")
            assert cid not in texts
            texts[cid] = raw.decode("utf-16-be")
        if array:
            assert next(tokens) == "]"
assert sorted(texts) == list(range(len(glyphs)))

bmp = b"".join(struct.pack(">H", value if value <= 65535 else 0) for value in glyphs)
(output / "gb1.zlib").write_bytes(zlib.compress(bmp, 9))
lines = ["// Code generated by generate.py; DO NOT EDIT.",
         "// Adobe 映射数据；源文件哈希见 SHA256SUMS，许可见 NOTICE。",
         "package cidmap", "const gb1Count = 30284", "var gb1Supplementary = map[int]rune{"]
for cid, value in enumerate(glyphs):
    if value > 65535:
        lines.append(f"{cid}: 0x{value:X},")
lines += ["}", "var gb1TextDifferences = map[int]string{"]
for cid, text in sorted(texts.items()):
    if glyphs[cid] == 0 or chr(glyphs[cid]) != text:
        lines.append(f"{cid}: {json.dumps(text, ensure_ascii=False)},")
lines += ["}", ""]
(output / "gb1_data.go").write_text("\n".join(lines))
(output / "SHA256SUMS").write_text("".join(
    f"{hashlib.sha256(data).hexdigest()}  {path}\n"
    for path, data in [(glyph_path, glyph_data), (text_path, text_data)]))
print(f"Generated {len(glyphs)} CIDs, {len(bmp)} uncompressed BMP bytes")
